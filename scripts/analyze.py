"""Does the rubric score track real outcomes? Usage: python scripts/analyze.py [--md results/VALIDATION.md]
Reads data/essays.csv. The main test holds the prompt and the judges fixed: inside one contest round,
how often does a winner outscore an essay that placed lower or lost?"""
import argparse, csv, io, os, statistics as st

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CRIT = ["answers_prompt", "specificity", "human_voice", "stories", "ideas_mechanism", "structure_ending"]
LOSE = ("runner-up", "finalist", "honorable-mention", "not-selected")


def rate(w, l, key):
    ok = n = 0
    for a in w:
        for b in l:
            x, y = key(a), key(b)
            n += 1
            ok += (x > y) + 0.5 * (x == y)
    return ok, n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--md")
    a = ap.parse_args()
    rows = list(csv.DictReader(io.open(os.path.join(ROOT, "data", "essays.csv"), encoding="utf-8")))
    for r in rows:
        r["total"] = int(r["total"])
    out = []
    p = lambda s="": out.append(s)

    by = {}
    for r in rows:
        by.setdefault(r["contest"], []).append(r)
    p("## Same-contest test")
    p()
    p("| Contest | Set | Winners | Lower | Winner higher |")
    p("|---|---|---:|---:|---:|")
    tot_ok = tot_n = 0
    per, per_set = [], {}
    crit = {c: [0, 0] for c in CRIT}
    for name, rs in sorted(by.items()):
        w = [r for r in rs if r["outcome"] == "winner"]
        l = [r for r in rs if r["outcome"] in LOSE]
        ok, n = rate(w, l, lambda r: r["total"])
        if not n:
            continue
        tot_ok, tot_n = tot_ok + ok, tot_n + n
        per.append(ok / n)
        s = "new" if all(r["set"] != "v1-corpus" for r in rs) else "v1"
        per_set.setdefault(s, []).append(ok / n)
        for c in CRIT:
            o, m = rate(w, l, lambda r: int(r[c]))
            crit[c][0] += o
            crit[c][1] += m
        p("| %s | %s | %d | %d | %d%% |" % (name, s, len(w), len(l), round(100 * ok / n)))
    p()
    p("All pairs: winner higher in **%d%%** of %d pairs. Each contest counted equally: **%d%%** over %d contests." % (
        round(100 * tot_ok / tot_n), tot_n, round(100 * st.mean(per)), len(per)))
    for s, v in sorted(per_set.items()):
        p("- %s contests: %d%% over %d contests" % (s, round(100 * st.mean(v)), len(v)))
    p()
    p("## Which criteria separate winners (same-contest pairs)")
    p()
    p("| Criterion | Winner scored higher |")
    p("|---|---:|")
    for c in sorted(CRIT, key=lambda c: -crit[c][0] / crit[c][1]):
        p("| %s | %d%% |" % (c, round(100 * crit[c][0] / crit[c][1])))
    p()

    again = [r for r in rows if r["v1_total"]]
    if again:
        d = [abs(r["total"] - int(r["v1_total"])) for r in again]
        bands = lambda t: "high" if t >= 72 else "mid" if t >= 50 else "low"
        same = sum(bands(r["total"]) == bands(int(r["v1_total"])) for r in again)
        xs, ys = [int(r["v1_total"]) for r in again], [r["total"] for r in again]
        p("## Judge consistency (same essay graded twice)")
        p()
        p("%d essays graded in two separate runs. Mean gap %.1f points, median %d, correlation %.2f, same band %d%%." % (
            len(again), st.mean(d), st.median(d), st.correlation(xs, ys), round(100 * same / len(again))))
        p()

    p("## Score by outcome")
    p()
    p("| Outcome | Essays | Mean score |")
    p("|---|---:|---:|")
    for o in ("winner",) + LOSE + ("unknown",):
        t = [r["total"] for r in rows if r["outcome"] == o]
        if t:
            p("| %s | %d | %.1f |" % (o, len(t), st.mean(t)))
    text = "\n".join(out)
    print(text)
    if a.md:
        io.open(os.path.join(ROOT, a.md), "w", encoding="utf-8").write(
            "# Validation\n\nGenerated by `python scripts/analyze.py --md %s`.\n\n%s\n" % (a.md, text))


if __name__ == "__main__":
    main()
